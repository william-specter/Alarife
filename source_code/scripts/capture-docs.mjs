import { chromium } from '@playwright/test';
const out = '../Documentation/screenshots';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
await page.goto('http://localhost:8000/login', { waitUntil: 'load' });
await page.fill('#email', 'admin@alarife.test');
await page.fill('#password', 'password');
await page.click('button[type=submit]');
await page.waitForURL('**/dashboard');
await page.waitForTimeout(2500);
await page.waitForFunction(() => Array.from(document.images).every((img) => img.complete));
await page.screenshot({ path: `${out}/admin-dashboard.png` });
await page.goto('http://localhost:8000/author/ancient-civilizations/overview', { waitUntil: 'load' });
await page.screenshot({ path: `${out}/admin-overview.png` });
await page.goto('http://localhost:8000/author/ancient-civilizations/articles/1/edit', { waitUntil: 'load' });
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/admin-editor.png` });
await page.goto('http://localhost:8000/author/ancient-civilizations/appearance', { waitUntil: 'load' });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/admin-appearance.png` });
await page.goto('http://localhost:8000/ancient-civilizations/articles/pyramids-of-giza', { waitUntil: 'load' });
await page.screenshot({ path: `${out}/reader-editorial-article.png` });
await page.goto('http://localhost:8000/atlas-of-shared-waters', { waitUntil: 'load' });
await page.screenshot({ path: `${out}/reader-atlas-home.png` });
await page.goto('http://localhost:8000/a-small-bestiary', { waitUntil: 'load' });
await page.screenshot({ path: `${out}/reader-nocturne-home.png` });
await browser.close();
