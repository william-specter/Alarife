import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
const base = process.env.OFFLINE_BASE ?? 'file:///tmp/opencode/offline/ancient-civilizations/';
await page.goto(base + 'index.html', { waitUntil: 'networkidle' });
await page.screenshot({ path: '/tmp/opencode/offline-home.png' });
console.log('HOME title:', await page.title());
console.log('CAROUSEL slides:', await page.locator('.carousel-slide').count());
await page.goto(base + 'articles/pyramids-of-giza/index.html', { waitUntil: 'networkidle' });
console.log('ARTICLE h1:', await page.locator('h1').first().textContent());
console.log('ARTICLE images:', await page.locator('.article-body img').count());
await page.screenshot({ path: '/tmp/opencode/offline-article.png' });
await page.goto(base + 'search/index.html?q=pyramid', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
console.log('SEARCH results:', await page.locator('.search-result').count());
console.log('SEARCH count:', await page.locator('[data-search-count]').textContent());
await page.screenshot({ path: '/tmp/opencode/offline-search.png' });
console.log('ERRORS', JSON.stringify(errors, null, 2));
await browser.close();
